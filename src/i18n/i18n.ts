const TABLES: Record<AppLanguage, Record<TranslationKey, string>> = { en: EN, ar: AR };

export function resolveLanguage(choice: LanguageChoice, systemLocale?: string | null): AppLanguage {
  if (choice === 'en' || choice === 'ar') return choice;
  return systemLocale?.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  const template = TABLES[language][key] ?? EN[key];
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function translateCount(
  language: AppLanguage,
  count: number,
  singularKey: TranslationKey,
  pluralKey: TranslationKey,
  values: TranslationValues = {},
): string {
  return translate(language, count === 1 ? singularKey : pluralKey, {
    ...values,
    count: formatLocalizedNumber(language, count),
  });
}

export function formatLocalizedNumber(language: AppLanguage, value: number): string {
  return new Intl.NumberFormat(language === 'ar' ? 'ar-u-nu-arab' : 'en-u-nu-latn', {
    useGrouping: false,
  }).format(value);
}
